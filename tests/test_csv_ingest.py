CLASSES = {"Benign", "Brute Force", "DoS Hulk", "Port Scanning", "Volumetric DDoS"}


def _db_hashes() -> dict[str, str]:
    return {str(p): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in (PROJECT_ROOT / "results").glob("*.db")}


def test_committed_sample_matches_the_generator():
    assert SAMPLE.read_text(encoding="utf-8") == build_sample_csv_text()


# --- valid labelled CSV: accuracy available ------------------------------------------
def test_labelled_csv_validates_and_reports_schema_and_classes():
    data = load_csv(SAMPLE)
    rep = data.report
    assert rep["rows_read"] == EXPECTED_CSV_ROWS == 43
    assert rep["rows_usable"] == EXPECTED_CSV_USABLE == 40
    assert rep["rows_dropped_nan_inf"] == 1                       # the 'Infinity' row
    assert rep["label"]["excluded_out_of_taxonomy"] == {"DoS slowloris": 2}
    assert rep["columns"]["present"] == 78 and rep["columns"]["missing"] == []
    assert rep["label"]["found"] and rep["label"]["column"] == "Label"   # raw ' Label' stripped
    assert rep["label"]["distribution"] == {c: 8 for c in CLASSES}
    assert rep["label"]["raw_distribution"]["SSH-Patator"] == 4         # raw -> canonical mapping
    from agentmeter.ingest.feature_map import META_COLUMNS
    assert data.labelled and list(data.features.columns) == META_COLUMNS + CIC_FEATURES


def test_label_is_isolated_from_features_and_from_the_rule_engine(monkeypatch):
    data = load_csv(SAMPLE)
    assert not any(c.lower() == "label" for c in data.features.columns)
    assert list(data.labels.columns) == ["flow_id", "label_raw", "label"]
    assert list(data.labels["flow_id"]) == list(data.features["flow_id"])
    seen = {}
    real = rules.select_flows

    def spy(df, rb, max_flows=None):
        seen["cols"] = list(df.columns)
        return real(df, rb, max_flows=max_flows)

    monkeypatch.setattr(rules, "select_flows", spy)
    run.process_csv(SAMPLE, write=False)
    assert not any(c.lower().startswith("label") for c in seen["cols"])


def test_process_csv_end_to_end_accuracy_available(tmp_path):
    before = _db_hashes()
    res = run.process_csv(SAMPLE, out_root=tmp_path, max_flows=20)
    out = tmp_path / "cicids2017_sample"
    assert sorted(p.name for p in out.iterdir()) == [
        "input.json", "labels.csv", "manifest.json", "schema_report.md",
        "selected_flows.csv", "selection_audit.json"]
    assert _db_hashes() == before and not list(tmp_path.rglob("*.db"))

    meta = json.loads((out / "input.json").read_text())
    assert meta["source_type"] == "csv" and meta["input_role"] == "labelled_csv"
    assert meta["evaluation_mode"] == "accuracy_available"
    assert meta["capabilities"] == {"resource_efficiency": True, "accuracy": True}
    assert meta["feature_match"]["status"] == "exact" and meta["feature_columns"] == CIC_FEATURES
    assert meta["rows_total"] == 40 and meta["rows_selected"] == 20
    assert "label" in meta["hidden_columns"] and "src_ip" in meta["hidden_columns"]
    assert set(meta["label_distribution_selected"]) <= CLASSES
    assert sum(meta["label_distribution_selected"].values()) == 20

    audit = json.loads((out / "selection_audit.json").read_text())
    assert len(audit["flows"]) == 20 and all(f["admitted_by"] and f["reason"] for f in audit["flows"])
    assert "typical_baseline" in audit["rules_fired"]

    sel = pd.read_csv(out / "selected_flows.csv")
    labels = pd.read_csv(out / "labels.csv")
    assert list(sel.columns) == SELECTED_COLUMNS
    assert list(labels["flow_id"]) == list(sel["flow_id"])
    assert "**accuracy_available**" in (out / "schema_report.md").read_text()
    assert res["input"].accuracy_available


