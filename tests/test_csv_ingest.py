# --- rejections -------------------------------------------------------------------
def _write(tmp_path, name, content):
    p = tmp_path / name
    (p.write_bytes if isinstance(content, bytes) else p.write_text)(content)
    return p


@pytest.mark.parametrize("name, content, msg", [
    ("cap.csv", b"\xd4\xc3\xb2\xa1" + b"\x00" * 40, "packet capture, not a CSV"),
    ("bin.csv", b"PK\x03\x04\x00\x00binary", "binary content"),
    ("empty.csv", "", "empty file"),
    ("other.csv", "name,age,city\nann,3,x\n", "none of the 78 feature columns"),
    ("ragged.csv", "Destination Port,Flow Duration\n1,2\n3,4,5,6\n", "not a readable CSV"),
])
def test_wrong_files_are_rejected_with_a_clear_reason(tmp_path, name, content, msg):
    with pytest.raises(CsvValidationError, match=msg):
        load_csv(_write(tmp_path, name, content))


def test_missing_features_rejected_unless_partial_and_rule_columns_still_required(tmp_path):
    df = pd.read_csv(DATASET).head(40)
    p = tmp_path / "subset.csv"
    df.drop(columns=["Idle Std", "Active Max"]).to_csv(p, index=False)
    with pytest.raises(CsvValidationError, match="2 of 78 CIC-IDS2017 feature columns missing"):
        load_csv(p)
    res = run.process_csv(p, allow_partial=True, write=False)
    meta = res["input"].metadata
    assert meta["feature_match"]["status"] == "partial"
    assert meta["feature_match"]["missing"] == ["Active Max", "Idle Std"]
    assert "Idle Std" not in meta["feature_columns"] and len(meta["feature_columns"]) == 76

    q = tmp_path / "norule.csv"
    df.drop(columns=["Flow Duration"]).to_csv(q, index=False)
    with pytest.raises(CsvValidationError, match="required by the flow-selection rules"):
        run.process_csv(q, allow_partial=True, write=False)


def test_header_only_all_invalid_and_colliding_columns_are_rejected(tmp_path):
    header = ",".join(CIC_FEATURES + ["label"])
    with pytest.raises(CsvValidationError, match="no data rows"):
        load_csv(_write(tmp_path, "h.csv", header + "\n"))
    row = ",".join(["Infinity"] * 78 + ["Benign"])
    with pytest.raises(CsvValidationError, match="no usable rows"):
        load_csv(_write(tmp_path, "inf.csv", header + "\n" + row + "\n"))
    only_oot = pd.read_csv(DATASET).head(5).assign(label="Heartbleed")
    only_oot.to_csv(tmp_path / "oot.csv", index=False)
    with pytest.raises(CsvValidationError, match="out-of-taxonomy"):
        load_csv(tmp_path / "oot.csv")
    with pytest.raises(CsvValidationError, match="collide"):
        load_csv(_write(tmp_path, "dup.csv", "Flow Duration, Flow Duration ,label\n1,2,Benign\n"))


# --- unified contract --------------------------------------------------------------
def test_contract_rejects_label_leak_and_misaligned_labels(tmp_path):
    res = run.process_csv(SAMPLE, out_root=tmp_path, max_flows=10)
    good = res["input"]
    leaked = good.selected.assign(label="x")
    with pytest.raises(InputContractError):
        unified.write_input_run(tmp_path / "bad1", unified.InputRun(good.metadata, leaked, good.labels))
    shuffled = good.labels.iloc[::-1].reset_index(drop=True)
    with pytest.raises(InputContractError, match="align"):
        unified.write_input_run(tmp_path / "bad2", unified.InputRun(good.metadata, good.selected, shuffled))
    loaded = load_input_run(tmp_path / "cicids2017_sample")
    assert loaded.accuracy_available and list(loaded.selected.columns) == SELECTED_COLUMNS


